/**
 * Helper to get Ekadashi by slug
 */
export function getEkadashiBySlug(slug) {
  if (!slug) return null;
  const normalized = String(slug).toLowerCase().trim();
  return EKADASHI_LIST.find(e => e.slug.toLowerCase() === normalized || e.id.toLowerCase() === normalized) || null;
}

/**
 * Helper to filter by Paksham
 */
export function getEkadashisByPaksham(paksham) {
  return EKADASHI_LIST.filter(e => e.paksham.includes(paksham));
}

/**
 * Helper to get Major Ekadashis
 */
export function getMajorEkadashis() {
  return EKADASHI_LIST.filter(e => e.isMajor);
}
